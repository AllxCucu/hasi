namespace Hasi.Core.Input;

/// <summary>Semantic commands. Screens react to commands, never to physical keys.</summary>
public enum Command
{
    /// <summary>The key has no binding; screens may still use <see cref="InputEvent.Character"/>.</summary>
    None,

    Next,
    Previous,
    First,
    Last,
    Activate,
    Back,
    Increase,
    Decrease,

    /// <summary>Delete the character before the cursor (Backspace) in text fields.</summary>
    DeletePrevious,

    // Global commands, handled by the shell on every screen.
    Help,
    RepeatLast,
    WhereAmI,
    StopSpeech,
    Exit,

    /// <summary>Turns diagnostic mode on or off (Ctrl+Shift+F12 / Ctrl+Shift+D).</summary>
    ToggleDiagnostic,
}

public static class CommandExtensions
{
    public static bool IsGlobal(this Command command) => command is
        Command.Help or Command.RepeatLast or Command.WhereAmI or Command.StopSpeech or Command.Exit
        or Command.ToggleDiagnostic;

    /// <summary>
    /// Whether a key held down keeps repeating the command. Only moving and adjusting do; holding
    /// Enter or Escape must never open, confirm or close several things in a row.
    /// </summary>
    public static bool RepeatsWhenHeld(this Command command) => command is
        Command.Next or Command.Previous or Command.Increase or Command.Decrease or Command.DeletePrevious
        or Command.None;
}

/// <param name="IsRepeat">Generated by the keyboard's auto-repeat while the key is held down.</param>
public sealed record InputEvent(Command Command, KeyChord Key, char? Character = null, bool IsRepeat = false);
